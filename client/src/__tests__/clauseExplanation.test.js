import { describe, it, before, after } from 'node:test';
import assert from 'node:assert/strict';
import React from 'react';
import { renderToString } from 'react-dom/server';
import { createServer } from 'vite';

describe('Clause Explanation Panel & Adapter', () => {
  let vite;
  let ClauseExplanationPanel;
  let mockAdapter;

  before(async () => {
    vite = await createServer({ server: { middlewareMode: true, hmr: false, ws: false } });
    const panelMod = await vite.ssrLoadModule('./src/components/ai/ClauseExplanationPanel.jsx');
    ClauseExplanationPanel = panelMod.default;
    mockAdapter = await vite.ssrLoadModule('./src/api/ai/mockAdapter.js');
  });

  after(async () => {
    if (vite) await vite.close();
  });

  const testClause = {
    id: 'c-payment',
    title: 'Payment Terms & Invoicing',
    legalText: 'The client shall pay the agreed fee within 15 days of invoice submission.',
    plainText: 'Describes how and when fees are paid.',
    source: 'Indian Contract Act, 1872',
  };

  it('renders nothing when isOpen is false', () => {
    const html = renderToString(React.createElement(ClauseExplanationPanel, {
      isOpen: false,
      clause: testClause,
      onClose: () => {},
    }));
    assert.equal(html, '');
  });

  it('renders clause ID, reviewed template text, and reviewed template badge', () => {
    const html = renderToString(React.createElement(ClauseExplanationPanel, {
      isOpen: true,
      clause: testClause,
      onClose: () => {},
    }));
    assert.ok(html.includes('ID: c-payment') || html.includes('c-payment'));
    assert.ok(html.includes('Payment Terms &amp; Invoicing') || html.includes('Payment Terms'));
    assert.ok(html.includes('Reviewed Template Clause'));
    assert.ok(html.includes('The client shall pay the agreed fee within 15 days of invoice submission.'));
    assert.ok(html.includes('not generated by AI'));
  });

  it('displays the AI-generated plain-language badge and persistent disclaimer', () => {
    const html = renderToString(React.createElement(ClauseExplanationPanel, {
      isOpen: true,
      clause: testClause,
      onClose: () => {},
    }));
    assert.ok(html.includes('AI-generated'));
    assert.ok(html.includes('Persistent Notice') || html.includes('AI explanations provide drafting assistance'));
  });

  it('mockExplainClause returns structured plain-language explanation for standard clauses', async () => {
    const res = await mockAdapter.mockExplainClause({
      clauseId: 'c-payment',
      clauseTitle: 'Payment Terms',
      legalText: testClause.legalText,
      consent: true,
    });
    assert.equal(res.clause_id, 'c-payment');
    assert.ok(res.plain_explanation.includes('fees') || res.plain_explanation.includes('billing'));
    assert.ok(Array.isArray(res.key_considerations));
    assert.ok(res.key_considerations.length > 0);
    assert.equal(res.needs_legal_review, false);
    assert.ok(res.disclaimer.includes('not legal advice'));
  });

  it('flags needs_legal_review when high-risk covenants are present', async () => {
    const riskyClause = {
      clauseId: 'c-risk',
      clauseTitle: 'Indemnity & Non-Compete',
      legalText: 'The freelancer agrees to unlimited liability and perpetual non-compete within India.',
      consent: true,
    };
    const res = await mockAdapter.mockExplainClause(riskyClause);
    assert.equal(res.needs_legal_review, true);
  });
});
